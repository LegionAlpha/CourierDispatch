namespace Orders.Tests.Infrastructure.Outbox;

[Trait("Category", "PostgreSQL")]
public sealed class OutboxPostgresTests : IAsyncLifetime
{
    private readonly string _databaseName = $"orders_outbox_test_{Guid.NewGuid():N}";
    private readonly FakeTimeProvider _time = new(new DateTimeOffset(2026, 11, 7, 0, 0, 0, TimeSpan.Zero));
    private string _adminConnection = string.Empty;
    private string _connectionString = string.Empty;
    private bool _databaseCreated;

    public async Task InitializeAsync()
    {
        var connection = new NpgsqlConnectionStringBuilder(Environment.GetEnvironmentVariable("ORDERS_TEST_POSTGRES")
            ?? throw new InvalidOperationException("ORDERS_TEST_POSTGRES is required."))
        { Pooling = false };
        _adminConnection = connection.ConnectionString;
        await using var admin = new NpgsqlConnection(_adminConnection);
        await admin.OpenAsync();
        await using var create = new NpgsqlCommand($"CREATE DATABASE \"{_databaseName}\"", admin);
        await create.ExecuteNonQueryAsync();
        _databaseCreated = true;
        connection.Database = _databaseName;
        _connectionString = connection.ConnectionString;
        await using var db = CreateDb();
        await db.Database.MigrateAsync();
    }

    public async Task DisposeAsync()
    {
        if (!_databaseCreated)
        {
            return;
        }

        await using var admin = new NpgsqlConnection(_adminConnection);
        await admin.OpenAsync();
        // This name is generated by this test instance, never taken from configuration.
        await using var drop = new NpgsqlCommand($"DROP DATABASE \"{_databaseName}\" WITH (FORCE)", admin);
        await drop.ExecuteNonQueryAsync();
    }

    [PostgresFact]
    public async Task CreateOrder_CommitsOrderAndEventTogether()
    {
        await using var db = CreateDb();
        var handler = new CreateOrderCommandHandler(new StubDeliveryEstimator(new DeliveryEstimate(12000, 8)),
            new OrderRepository(db), db, new OutboxWriter(db), _time);

        var result = await handler.Handle(new CreateOrderCommand(25.2, 55.2, 25.3, 55.3), CancellationToken.None);

        await using var verification = CreateDb();
        Assert.Equal(result.Id, (await verification.Orders.SingleAsync()).Id);
        var message = await verification.OutboxMessages.SingleAsync();
        Assert.Equal(OutboxWriter.OrderCreatedType, message.Type);
        Assert.Equal(new OrderCreated(result.Id, result.FromLatitude, result.FromLongitude,
            result.ToLatitude, result.ToLongitude, result.PriceMinor, result.EtaMinutes, result.CreatedAt),
            JsonSerializer.Deserialize<OrderCreated>(message.Payload, OutboxWriter.SerializerOptions));
        Assert.Null(message.ProcessedAt);
        Assert.Equal(0, message.Attempts);
    }

    [PostgresFact]
    public async Task OutboxInsertFails_RollsBackOrderToo()
    {
        await using var db = CreateDb();
        var order = Order.Create(GeoPoint.Create(25, 55), GeoPoint.Create(26, 56), 12000, 8, _time.GetUtcNow());
        db.Orders.Add(order);
        new OutboxWriter(db).Add(CreateEvent(order.Id));
        db.OutboxMessages.Local.Single().Payload = "not valid json";

        await Assert.ThrowsAsync<DbUpdateException>(() => db.SaveChangesAsync());

        await using var verification = CreateDb();
        Assert.Empty(await verification.Orders.ToListAsync());
        Assert.Empty(await verification.OutboxMessages.ToListAsync());
    }

    [PostgresFact]
    public async Task PublishFails_RetainsEventAndRetriesAfterBackoffWithFreshContext()
    {
        var id = await SeedAsync();
        var failing = new TestPublisher((_, _) => throw new IOException("RabbitMQ offline"));
        await using (var db = CreateDb())
        {
            Assert.True(await Processor(db, failing).ProcessNextAsync(CancellationToken.None));
        }

        await using (var db = CreateDb())
        {
            var pending = await db.OutboxMessages.SingleAsync();
            Assert.Null(pending.ProcessedAt);
            Assert.Equal(1, pending.Attempts);
            Assert.Contains("RabbitMQ offline", pending.LastError);
            Assert.Equal(_time.GetUtcNow().AddSeconds(5), pending.NextAttemptAt);
        }

        var succeeding = new TestPublisher();
        await using (var db = CreateDb())
        {
            Assert.False(await Processor(db, succeeding).ProcessNextAsync(CancellationToken.None));
        }
        Assert.Empty(succeeding.MessageIds);
        _time.Advance(TimeSpan.FromSeconds(5));
        await using (var db = CreateDb())
        {
            Assert.True(await Processor(db, succeeding).ProcessNextAsync(CancellationToken.None));
        }

        Assert.Equal(id, Assert.Single(succeeding.MessageIds));
        await using var verification = CreateDb();
        var sent = await verification.OutboxMessages.SingleAsync();
        Assert.Equal(_time.GetUtcNow(), sent.ProcessedAt);
        Assert.Equal(2, sent.Attempts);
        Assert.Null(sent.LastError);
        Assert.False(await Processor(verification, succeeding).ProcessNextAsync(CancellationToken.None));
    }

    [PostgresFact]
    public async Task SaveAfterPublishFails_RetryUsesSameMessageId()
    {
        var id = await SeedAsync();
        var publisher = new TestPublisher();
        await using (var db = CreateDb(new FailSaveInterceptor()))
        {
            await Assert.ThrowsAsync<IOException>(() => Processor(db, publisher).ProcessNextAsync(CancellationToken.None));
        }
        await using (var db = CreateDb())
        {
            var pending = await db.OutboxMessages.SingleAsync();
            Assert.Null(pending.ProcessedAt);
            Assert.Equal(0, pending.Attempts);
            Assert.True(await Processor(db, publisher).ProcessNextAsync(CancellationToken.None));
        }

        Assert.Equal(new[] { id, id }, publisher.MessageIds);
        await using var verification = CreateDb();
        Assert.NotNull((await verification.OutboxMessages.SingleAsync()).ProcessedAt);
    }

    [PostgresFact]
    public async Task ConcurrentWorkers_SkipLockedMessageAndProcessAnother()
    {
        var firstId = await SeedAsync();
        _time.Advance(TimeSpan.FromSeconds(1));
        var secondId = await SeedAsync();
        var started = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
        var release = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
        var firstPublisher = new TestPublisher(async (_, token) =>
        {
            started.SetResult();
            await release.Task.WaitAsync(token);
        });
        await using var firstDb = CreateDb();
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(10));
        var firstTask = Processor(firstDb, firstPublisher).ProcessNextAsync(timeout.Token);
        try
        {
            await started.Task.WaitAsync(timeout.Token);
            await using var secondDb = CreateDb();
            var secondPublisher = new TestPublisher();
            Assert.True(await Processor(secondDb, secondPublisher).ProcessNextAsync(timeout.Token));
            Assert.Equal(secondId, Assert.Single(secondPublisher.MessageIds));
        }
        finally
        {
            release.TrySetResult();
            await firstTask;
        }

        Assert.Equal(firstId, Assert.Single(firstPublisher.MessageIds));
        await using var verification = CreateDb();
        Assert.Equal(2, await verification.OutboxMessages.CountAsync(message => message.ProcessedAt != null));
    }

    [PostgresFact]
    public async Task ShutdownDuringPublish_RollsBackAndLeavesEventPending()
    {
        var id = await SeedAsync();
        using var cancellation = new CancellationTokenSource();
        var publisher = new TestPublisher((_, token) =>
        {
            cancellation.Cancel();
            return Task.FromCanceled(token);
        });
        await using (var db = CreateDb())
        {
            await Assert.ThrowsAnyAsync<OperationCanceledException>(() =>
                Processor(db, publisher).ProcessNextAsync(cancellation.Token));
        }

        await using var verification = CreateDb();
        var pending = await verification.OutboxMessages.SingleAsync();
        Assert.Equal(id, pending.Id);
        Assert.Null(pending.ProcessedAt);
        Assert.Null(pending.LastError);
        Assert.Equal(0, pending.Attempts);
    }

    [PostgresFact]
    public async Task BadMessage_DoesNotBlockOtherMessagesAndBackoffIsCapped()
    {
        var badId = await SeedAsync();
        var goodId = await SeedAsync();
        var publisher = new TestPublisher((message, _) => message.Id == badId
            ? Task.FromException(new InvalidOperationException(new string('x', 3000)))
            : Task.CompletedTask);

        // The first message fails; a different pending message can still be sent.
        await using (var db = CreateDb())
        {
            var bad = await db.OutboxMessages.SingleAsync(message => message.Id == badId);
            bad.Attempts = 100;
            await db.SaveChangesAsync();
        }
        for (var i = 0; i < 2; i++)
        {
            await using var db = CreateDb();
            Assert.True(await Processor(db, publisher).ProcessNextAsync(CancellationToken.None));
        }

        await using var verification = CreateDb();
        var failed = await verification.OutboxMessages.SingleAsync(message => message.Id == badId);
        Assert.Null(failed.ProcessedAt);
        Assert.Equal(_time.GetUtcNow().AddSeconds(300), failed.NextAttemptAt);
        Assert.Equal(2000, failed.LastError!.Length);
        Assert.NotNull((await verification.OutboxMessages.SingleAsync(message => message.Id == goodId)).ProcessedAt);
    }

    private OrdersDbContext CreateDb(params IInterceptor[] interceptors) => new(
        new DbContextOptionsBuilder<OrdersDbContext>().UseNpgsql(_connectionString)
            .UseSnakeCaseNamingConvention().AddInterceptors(interceptors).Options);

    private OutboxProcessor Processor(OrdersDbContext db, IOutboxMessagePublisher publisher) => new(
        db, publisher, _time, Options.Create(new OutboxOptions()), NullLogger<OutboxProcessor>.Instance);

    private async Task<Guid> SeedAsync()
    {
        await using var db = CreateDb();
        new OutboxWriter(db).Add(CreateEvent(Guid.NewGuid()));
        var id = db.OutboxMessages.Local.Single().Id;
        await db.SaveChangesAsync();
        return id;
    }

    private OrderCreated CreateEvent(Guid orderId) => new(orderId, 25, 55, 26, 56, 12000, 8, _time.GetUtcNow());

    private sealed class TestPublisher(Func<OutboxMessage, CancellationToken, Task>? publish = null) : IOutboxMessagePublisher
    {
        public List<Guid> MessageIds { get; } = [];

        public Task PublishAsync(OutboxMessage message, CancellationToken cancellationToken)
        {
            MessageIds.Add(message.Id);
            return publish?.Invoke(message, cancellationToken) ?? Task.CompletedTask;
        }
    }

    private sealed class FailSaveInterceptor : SaveChangesInterceptor
    {
        public override ValueTask<InterceptionResult<int>> SavingChangesAsync(
            DbContextEventData eventData, InterceptionResult<int> result, CancellationToken cancellationToken = default) =>
            throw new IOException("Database save failed after the broker accepted the message.");
    }
}
