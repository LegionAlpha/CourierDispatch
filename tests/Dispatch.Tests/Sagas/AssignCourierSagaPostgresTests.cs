[Trait("Category", "PostgreSQL")]
public sealed class AssignCourierSagaPostgresTests : IAsyncLifetime
{
    private readonly string _databaseName = $"dispatch_saga_test_{Guid.NewGuid():N}";
    private string _adminConnection = string.Empty;
    private string _connectionString = string.Empty;
    private bool _databaseCreated;

    public async Task InitializeAsync()
    {
        var connection = new NpgsqlConnectionStringBuilder(Environment.GetEnvironmentVariable("DISPATCH_TEST_POSTGRES")
            ?? throw new InvalidOperationException("DISPATCH_TEST_POSTGRES is required."))
        { Pooling = false };
        _adminConnection = connection.ConnectionString;
        await using var admin = new NpgsqlConnection(_adminConnection);
        await admin.OpenAsync();
        await using var create = new NpgsqlCommand($"CREATE DATABASE \"{_databaseName}\"", admin);
        await create.ExecuteNonQueryAsync();
        _databaseCreated = true;
        connection.Database = _databaseName;
        _connectionString = connection.ConnectionString;
        await using var db = CreateDb();
        await db.Database.MigrateAsync();
    }

    public async Task DisposeAsync()
    {
        if (!_databaseCreated)
        {
            return;
        }

        await using var admin = new NpgsqlConnection(_adminConnection);
        await admin.OpenAsync();
        // This database name is generated by this test instance, not supplied by the user.
        await using var drop = new NpgsqlCommand($"DROP DATABASE \"{_databaseName}\" WITH (FORCE)", admin);
        await drop.ExecuteNonQueryAsync();
    }

    [PostgresFact]
    public async Task OrderCreated_PersistsAssignedSagaCorrelatedByOrderId()
    {
        var selector = new ControlledSelector();
        await using var services = CreateServices(selector);
        var (harness, observer) = await StartAsync(services);
        var message = CreateEvent();
        var messageId = Guid.NewGuid();

        await harness.Bus.Publish(message, context => context.MessageId = messageId);
        await WaitUntilAsync(() => observer.Completed.Count == 1);

        await using var db = CreateDb();
        var saga = await db.AssignCourierSagas.SingleAsync();
        Assert.Equal(message.OrderId, saga.CorrelationId);
        Assert.Equal("Assigned", saga.CurrentState);
        Assert.Equal(StubCourierSelector.CourierId, saga.CourierId);
        Assert.Equal(messageId, saga.InitialMessageId);
        Assert.Equal(message.FromLatitude, saga.PickupLatitude);
        Assert.Equal(message.FromLongitude, saga.PickupLongitude);
        Assert.Equal(message.CreatedAt, saga.OrderCreatedAt);
        Assert.NotNull(saga.AssignedAt);
        Assert.True(saga.AssignedAt >= saga.StartedAt);
        Assert.Equal(1, selector.Calls);
        Assert.Empty(observer.Faults);
        var outgoing = await db.OutboxMessages.SingleAsync();
        Assert.Null(outgoing.ProcessedAt);
        var assigned = JsonSerializer.Deserialize<CourierAssigned>(outgoing.Payload, OutboxWriter.SerializerOptions)!;
        Assert.Equal(saga.CorrelationId, assigned.OrderId);
        Assert.Equal(saga.CourierId, assigned.CourierId);
        // PostgreSQL stores microseconds; the event retains the original timestamp precision.
        Assert.True(Math.Abs((assigned.AssignedAt - saga.AssignedAt!.Value).Ticks) < TimeSpan.TicksPerMicrosecond);
        Assert.Empty(harness.Published.Select<CourierAssigned>());
    }

    [PostgresFact]
    public async Task RepeatedOrder_WithSameOrNewMessageId_DoesNotReassign()
    {
        var selector = new ControlledSelector();
        await using var services = CreateServices(selector);
        var (harness, observer) = await StartAsync(services);
        var message = CreateEvent();
        var messageId = Guid.NewGuid();
        await harness.Bus.Publish(message, context => context.MessageId = messageId);
        await WaitUntilAsync(() => observer.Completed.Count == 1);
        var before = await LoadAsync();

        await harness.Bus.Publish(message, context => context.MessageId = messageId);
        await harness.Bus.Publish(message with { FromLatitude = 10 });
        await WaitUntilAsync(() => observer.Completed.Count == 3);

        var after = await LoadAsync();
        Assert.Equal(before.CourierId, after.CourierId);
        Assert.Equal(before.AssignedAt, after.AssignedAt);
        Assert.Equal(before.PickupLatitude, after.PickupLatitude);
        Assert.Equal(before.InitialMessageId, after.InitialMessageId);
        Assert.Equal(1, selector.Calls);
        Assert.Empty(observer.Faults);
        await using var verification = CreateDb();
        Assert.Single(await verification.OutboxMessages.ToListAsync());
    }

    [PostgresFact]
    public async Task NewBusInstance_LoadsAssignedStateWithoutCallingSelector()
    {
        var message = CreateEvent();
        await using var first = CreateServices(new ControlledSelector());
        var (harness, observer) = await StartAsync(first);
        await harness.Bus.Publish(message);
        await WaitUntilAsync(() => observer.Completed.Count == 1);
        await harness.Stop();
        // Stop the old bus but retain its logger until both test hosts are disposed:
        // MassTransit carries an ambient logging context within this test execution.
        var before = await LoadAsync();
        var selector = new ControlledSelector { Failure = new IOException("Must not reassign") };
        await using var second = CreateServices(selector);
        var (restarted, restartedObserver) = await StartAsync(second);

        await restarted.Bus.Publish(message);
        await WaitUntilAsync(() => restartedObserver.Completed.Count == 1);

        var after = await LoadAsync();
        Assert.Equal(before.AssignedAt, after.AssignedAt);
        Assert.Equal(before.CourierId, after.CourierId);
        Assert.Equal(0, selector.Calls);
        Assert.Empty(restartedObserver.Faults);
    }

    [PostgresFact]
    public async Task ConcurrentInitialDeliveries_CreateOneAssignment()
    {
        var selector = new ControlledSelector();
        await using var services = CreateServices(selector);
        var (harness, observer) = await StartAsync(services);
        var message = CreateEvent();

        await Task.WhenAll(Enumerable.Range(0, 8).Select(_ => harness.Bus.Publish(message)));
        await WaitUntilAsync(() => observer.Completed.Count == 8);

        Assert.Equal("Assigned", (await LoadAsync()).CurrentState);
        Assert.Equal(1, selector.Calls);
        Assert.Empty(observer.Faults);
        await using var verification = CreateDb();
        Assert.Single(await verification.OutboxMessages.ToListAsync());
    }

    [PostgresFact]
    public async Task SelectorFails_RollsBackSaga_AndRedeliveryCanSucceed()
    {
        var selector = new ControlledSelector { Failure = new IOException("Selector unavailable") };
        await using var services = CreateServices(selector);
        var (harness, observer) = await StartAsync(services);
        var message = CreateEvent();
        var messageId = Guid.NewGuid();

        await harness.Bus.Publish(message, context => context.MessageId = messageId);
        Assert.True(await harness.Published.Any<Fault<OrderCreated>>());
        await using (var db = CreateDb())
        {
            Assert.Empty(await db.AssignCourierSagas.ToListAsync());
            Assert.Empty(await db.OutboxMessages.ToListAsync());
        }

        selector.Failure = null;
        await harness.Bus.Publish(message, context => context.MessageId = messageId);
        await WaitUntilAsync(() => observer.Completed.Count == 1);

        Assert.Equal("Assigned", (await LoadAsync()).CurrentState);
        Assert.Equal(2, selector.Calls);
    }

    [PostgresFact]
    public async Task DatabaseSaveFailsAfterSelection_RollsBackAndAllowsRedelivery()
    {
        var selector = new ControlledSelector();
        await using var services = CreateServices(selector, new FailAssignmentSaveOnce());
        var (harness, observer) = await StartAsync(services);
        var message = CreateEvent();
        var messageId = Guid.NewGuid();

        await harness.Bus.Publish(message, context => context.MessageId = messageId);
        Assert.True(await harness.Published.Any<Fault<OrderCreated>>());
        await using (var db = CreateDb())
        {
            Assert.Empty(await db.AssignCourierSagas.ToListAsync());
            Assert.Empty(await db.OutboxMessages.ToListAsync());
        }
        await harness.Bus.Publish(message, context => context.MessageId = messageId);
        await WaitUntilAsync(() => observer.Completed.Count == 1);

        Assert.Equal("Assigned", (await LoadAsync()).CurrentState);
        Assert.Equal(2, selector.Calls);
    }

    [PostgresFact]
    public async Task EmptyCourierId_DoesNotPersistAnAssignment()
    {
        var selector = new ControlledSelector { CourierId = Guid.Empty };
        await using var services = CreateServices(selector);
        var (harness, _) = await StartAsync(services);

        await harness.Bus.Publish(CreateEvent());
        Assert.True(await harness.Published.Any<Fault<OrderCreated>>());

        await using var db = CreateDb();
        Assert.Empty(await db.AssignCourierSagas.ToListAsync());
    }

    private ServiceProvider CreateServices(ICourierSelector selector, params IInterceptor[] interceptors) =>
        new ServiceCollection()
            .AddLogging()
            .AddSingleton(TimeProvider.System)
            .AddSingleton(selector)
            .AddScoped<AssignCourierActivity>()
            .AddScoped<IOutboxWriter, OutboxWriter>()
            .AddDbContext<DispatchDbContext>(options => options.UseNpgsql(_connectionString)
                .UseSnakeCaseNamingConvention().AddInterceptors(interceptors))
            .AddMassTransitTestHarness(registration =>
            {
                registration.AddAssignCourierSaga();
                registration.SetTestTimeouts(testTimeout: TimeSpan.FromSeconds(20));
                registration.UsingInMemory((context, bus) =>
                    bus.ReceiveEndpoint(AssignCourierSagaRegistration.QueueName,
                        endpoint => endpoint.ConfigureAssignCourierSaga(context)));
            })
            .BuildServiceProvider(true);

    private static async Task<(ITestHarness Harness, ConsumeObserver Observer)> StartAsync(ServiceProvider services)
    {
        var harness = services.GetRequiredService<ITestHarness>();
        await harness.Start();
        var observer = new ConsumeObserver();
        harness.Bus.ConnectConsumeObserver(observer);
        return (harness, observer);
    }

    private DispatchDbContext CreateDb() => new(new DbContextOptionsBuilder<DispatchDbContext>()
        .UseNpgsql(_connectionString).UseSnakeCaseNamingConvention().Options);

    private async Task<AssignCourierState> LoadAsync()
    {
        await using var db = CreateDb();
        return await db.AssignCourierSagas.SingleAsync();
    }

    private static async Task WaitUntilAsync(Func<bool> completed)
    {
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(20));
        while (!completed())
        {
            await Task.Delay(25, timeout.Token);
        }
    }

    private static OrderCreated CreateEvent() => new(Guid.NewGuid(), 25, 55, 26, 56, 12000, 8,
        new DateTimeOffset(2026, 11, 7, 0, 0, 0, TimeSpan.Zero));

    private sealed class ControlledSelector : ICourierSelector
    {
        private int _calls;
        public int Calls => _calls;
        public Exception? Failure { get; set; }
        public Guid CourierId { get; set; } = StubCourierSelector.CourierId;

        public Task<Guid> SelectAsync(Guid orderId, GeoPoint pickup, CancellationToken cancellationToken)
        {
            Interlocked.Increment(ref _calls);
            cancellationToken.ThrowIfCancellationRequested();
            return Failure is not null ? Task.FromException<Guid>(Failure) : Task.FromResult(CourierId);
        }
    }

    private sealed class ConsumeObserver : IConsumeObserver
    {
        public ConcurrentQueue<Guid> Completed { get; } = new();
        public ConcurrentQueue<Exception> Faults { get; } = new();

        public Task PreConsume<T>(ConsumeContext<T> context) where T : class => Task.CompletedTask;

        public Task PostConsume<T>(ConsumeContext<T> context) where T : class
        {
            if (context.Message is OrderCreated message)
            {
                Completed.Enqueue(message.OrderId);
            }
            return Task.CompletedTask;
        }

        public Task ConsumeFault<T>(ConsumeContext<T> context, Exception exception) where T : class
        {
            Faults.Enqueue(exception);
            return Task.CompletedTask;
        }
    }

    private sealed class FailAssignmentSaveOnce : SaveChangesInterceptor
    {
        private int _remainingFailures = 1;

        public override ValueTask<InterceptionResult<int>> SavingChangesAsync(
            DbContextEventData eventData, InterceptionResult<int> result, CancellationToken cancellationToken = default)
        {
            if (eventData.Context!.ChangeTracker.Entries<AssignCourierState>()
                .Any(entry => entry.Entity.CurrentState == "Assigned")
                && Interlocked.Exchange(ref _remainingFailures, 0) == 1)
            {
                throw new IOException("Database save failed after selection");
            }
            return ValueTask.FromResult(result);
        }
    }
}
